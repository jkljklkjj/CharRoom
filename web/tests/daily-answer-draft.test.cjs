const test=require('node:test'),assert=require('node:assert/strict'),path=require('node:path')
const {loadTs}=require('./helpers.cjs')
const file=path.resolve(__dirname,'../src/utils/dailyAnswerDraft.ts')
const storage=()=>{const data=new Map();return {getItem:key=>data.get(key)||null,setItem:(key,value)=>data.set(key,String(value)),removeItem:key=>data.delete(key)}}
test('daily drafts are isolated by account/day and publication clears only the submitted revision',async()=>{
  const {exports:drafts}=await loadTs(file,{localStorage:storage(),crypto:require('node:crypto').webcrypto})
  const submitted=drafts.saveDailyAnswerDraft('A','2026-10-28','first')
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28').text,'first')
  assert.equal(drafts.loadDailyAnswerDraft('B','2026-10-28'),null)
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-29'),null)
  drafts.saveDailyAnswerDraft('A','2026-10-28','second')
  drafts.clearSubmittedDailyAnswer(submitted)
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28').text,'second')
  drafts.saveDailyAnswerDraft('A','2026-10-28','first')
  drafts.clearSubmittedDailyAnswer(submitted)
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28').text,'first','editing back to identical text still creates a newer revision')
  const final=drafts.saveDailyAnswerDraft('A','2026-10-28','final');drafts.clearSubmittedDailyAnswer(final)
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28'),null)
})
test('an intentionally empty answer draft remains empty, and storage failures do not prevent editing',async()=>{
  const {exports:drafts}=await loadTs(file,{localStorage:storage(),crypto:require('node:crypto').webcrypto})
  drafts.saveDailyAnswerDraft('A','2026-10-28','')
  assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28').text,'')
  drafts.clearDailyAnswerDraft('A');assert.equal(drafts.loadDailyAnswerDraft('A','2026-10-28'),null)
  const failing=await loadTs(file,{crypto:require('node:crypto').webcrypto,localStorage:{getItem(){throw Error('disabled')},setItem(){throw Error('quota')},removeItem(){}}})
  assert.equal(failing.exports.saveDailyAnswerDraft('A','2026-10-28','text'),null)
})
