const test = require('node:test'), assert = require('node:assert/strict'), path = require('node:path')
const { IDBFactory, IDBKeyRange } = require('fake-indexeddb')
const { loadTs } = require('./helpers.cjs')
test('outbox isolates owners and retains failed messages until matching ACK or explicit retry', async () => {
  const { exports: queue } = await loadTs(path.resolve(__dirname, '../src/services/offlineQueue.ts'), { indexedDB: new IDBFactory(), IDBKeyRange })
  const message = { type: 1, chat: { messageId: 'same-id', content: 'fixture' } }
  await queue.saveToQueue('A', message, new ArrayBuffer(4), {})
  await queue.saveToQueue('B', message, new ArrayBuffer(4), {})
  assert.equal((await queue.getAllPending('A')).length, 1)
  await queue.markAttempt('A', 'same-id')
  assert.equal((await queue.getDuePending('A', Date.now())).length, 0)
  await queue.markFailed('A', 'same-id')
  assert.equal((await queue.getAllPending('A'))[0].state, 'failed')
  await queue.removeMessage('B', 'same-id')
  assert.equal((await queue.getAllPending('B')).length, 0)
  assert.equal((await queue.getAllPending('A')).length, 1)
  await queue.retryMessage('A', 'same-id')
  assert.equal((await queue.getDuePending('A', Date.now(), 1)).length, 1)
  assert.equal((await queue.getPending('A', 'same-id')).accountId, 'A')
  assert.equal((await queue.getAllPending('A'))[0].retryCount, 0)
})
